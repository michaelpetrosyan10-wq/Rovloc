#!/usr/bin/env python3
"""Uploads the generated texture maps to Roblox (Open Cloud Assets API) within a monthly budget and records them.

    ROBLOX_API_KEY=... ROBLOX_CREATOR_ID=... python3 tools/textures/upload.py --budget 100
    python3 tools/textures/upload.py --dry-run          print the requests that would be sent; change nothing
    python3 tools/textures/upload.py --write-only       re-render the Luau / model files from the upload log

Run tools/textures/generate.py first: it writes the PNGs and out/meta.json (sha256 + reference albedo per map).

Budget: Open Cloud allows 100 image uploads a month with an ID-verified account (10 without). `--budget` is the
monthly allowance; uploads already logged this calendar month (UTC) count against it, so re-running the workflow
in the same month never overspends. Maps go up in the manifest's `uploadOrder` (most visible first). A map that has
been uploaded once is never uploaded again: the log keeps its decal id and image id; a map Roblox rejected is only
retried when the generator changes its pixels.

The manifest's `assetType` picks what each upload creates. An "Image" upload's asset id is the image id itself and is
ready as soon as moderation approves it. A "Decal" upload wraps the image, which is then resolved through asset
delivery (that needs an extra API key permission). A map uploaded as a Decal whose image id never resolved is uploaded
once more under the manifest's current type; its earlier upload stays in the log and counts against its month. The
first Image upload of a run is checked: if Roblox answers with any other asset type the run stops, so a wrong type is
never repeated 45 times. Maps under moderation review or still processing stay out of the game and are re-checked on
the next run without re-uploading.

Writes src/ReplicatedStorage/Shared/Config/TextureAssets.luau (image ids of the maps that are ready + the upload
log) and src/MaterialService/RovlocTextures.model.json (one MaterialVariant per texture x base material whose
ColorMap is ready). The API key and creator id are read from the environment and never printed.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
LUAU = os.path.join(ROOT, "src", "ReplicatedStorage", "Shared", "Config", "TextureAssets.luau")
MODEL = os.path.join(ROOT, "src", "MaterialService", "RovlocTextures.model.json")
API = "https://apis.roblox.com"
MAPS = ("ColorMap", "NormalMap", "RoughnessMap", "MetalnessMap")
LOG_OPEN = "--[==[ upload-log"
LOG_CLOSE = "]==]"
PENDING = ("processing", "reviewing", "unresolved")


# -- record ---------------------------------------------------------------------------------------------------


def read_log(path: str | None = None) -> dict:
    """The upload log embedded at the end of TextureAssets.luau ({} when there is none yet)."""
    path = path or LUAU
    if not os.path.exists(path):
        return {"version": 1, "maps": {}}
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    start = text.find(LOG_OPEN)
    if start < 0:
        return {"version": 1, "maps": {}}
    end = text.find(LOG_CLOSE, start)
    if end < 0:
        raise SystemExit(f"{path}: upload log is not closed")
    log = json.loads(text[start + len(LOG_OPEN) : end])
    log.setdefault("maps", {})
    return log


def lua_number(x: float) -> str:
    s = f"{x:.4f}".rstrip("0")
    return s + "0" if s.endswith(".") else s


def render_luau(manifest: dict, log: dict) -> str:
    lines = [
        "--!strict",
        "-- GENERATED by tools/textures/upload.py (the Textures workflow): do not edit by hand.",
        "-- Roblox image ids of the generated PBR textures (tools/textures/manifest.json), per texture and map, for the",
        "-- maps that are uploaded and approved. A texture dresses its Palette keys once its ColorMap is here (and its",
        "-- MaterialVariants are in MaterialService); with no entries the game is untextured, exactly as before. The",
        "-- upload log after the return is the workflow's memory, so no map is ever uploaded twice.",
        "",
        "export type Entry = {",
        "\tColorMap: number?,",
        "\tNormalMap: number?,",
        "\tRoughnessMap: number?,",
        "\tMetalnessMap: number?,",
        "\treference: Color3?, -- albedo of the colour map's base layer; MaterialLibrary tints parts relative to it",
        "}",
        "",
    ]
    body = []
    for m in manifest["materials"]:
        ready = {k: v for k, v in ready_maps(log, m["id"]).items()}
        if not ready:
            continue
        body.append(f"\t{m['id']} = {{")
        for map_name in MAPS:
            if map_name in ready:
                body.append(f"\t\t{map_name} = {ready[map_name]['imageId']},")
        ref = (ready.get("ColorMap") or {}).get("reference")
        if ref:
            body.append(f"\t\treference = Color3.new({', '.join(lua_number(c) for c in ref)}),")
        body.append("\t},")
    if body:
        lines.append("local TextureAssets: { [string]: Entry } = {")
        lines.extend(body)
        lines.append("}")
    else:
        lines.append("local TextureAssets: { [string]: Entry } = {}")
    lines += ["", "return table.freeze(TextureAssets)", "", LOG_OPEN]
    lines.append(json.dumps(log, indent="\t", sort_keys=True))
    lines.append(LOG_CLOSE)
    return "\n".join(lines) + "\n"


def ready_maps(log: dict, texture: str) -> dict:
    out = {}
    for map_name in MAPS:
        rec = log["maps"].get(f"{texture}/{map_name}")
        if rec and rec.get("state") == "ready" and rec.get("imageId"):
            out[map_name] = rec
    return out


def render_model(manifest: dict, log: dict) -> str:
    children = []
    prefix = manifest["variantPrefix"]
    for m in manifest["materials"]:
        if m["kind"] != "variant":
            continue
        ready = ready_maps(log, m["id"])
        if "ColorMap" not in ready:
            continue
        for base in m["bases"]:
            props: dict = {"BaseMaterial": base}
            for map_name in MAPS:
                if map_name in ready:
                    props[f"{map_name}Content"] = f"rbxassetid://{ready[map_name]['imageId']}"
            props["StudsPerTile"] = m["studsPerTile"]
            props["MaterialPattern"] = m["pattern"]
            children.append({"name": f"{prefix}{m['id']}_{base}", "className": "MaterialVariant", "properties": props})
    return json.dumps({"className": "Folder", "children": children}, indent=2) + "\n"


def write_outputs(manifest: dict, log: dict, luau: str | None = None, model: str | None = None):
    luau = luau or LUAU
    model = model or MODEL
    os.makedirs(os.path.dirname(model), exist_ok=True)
    with open(luau, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_luau(manifest, log))
    with open(model, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_model(manifest, log))


# -- Open Cloud -----------------------------------------------------------------------------------------------


class Cloud:
    def __init__(self, api_key: str, creator_id: str):
        self._key = api_key
        self._creator = creator_id

    def _request(self, method: str, url: str, body: bytes | None = None, headers: dict | None = None):
        host = urllib.parse.urlparse(url).hostname or ""
        hdrs = dict(headers or {})
        if host == "roblox.com" or host.endswith(".roblox.com"):
            hdrs["x-api-key"] = self._key  # only ever sent to Roblox hosts
        req = urllib.request.Request(url, data=body, method=method, headers=hdrs)
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                return resp.status, resp.read()
        except urllib.error.HTTPError as err:
            return err.code, err.read()
        except (urllib.error.URLError, TimeoutError) as err:
            return 0, str(err).encode()

    def create(self, path: str, display: str, description: str, asset_type: str):
        request = {
            "assetType": asset_type,
            "displayName": display,
            "description": description,
            "creationContext": {"creator": {"userId": self._creator}},
        }
        boundary = "rovloc-" + uuid.uuid4().hex
        with open(path, "rb") as fh:
            data = fh.read()
        parts = [
            f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n\r\n".encode(),
            json.dumps(request).encode(),
            f"\r\n--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; "
            f"filename=\"{os.path.basename(path)}\"\r\nContent-Type: image/png\r\n\r\n".encode(),
            data,
            f"\r\n--{boundary}--\r\n".encode(),
        ]
        return self._request(
            "POST", f"{API}/assets/v1/assets", b"".join(parts), {"Content-Type": f"multipart/form-data; boundary={boundary}"}
        )

    def operation(self, op_path: str):
        op_id = op_path.split("/")[-1]
        return self._request("GET", f"{API}/assets/v1/operations/{urllib.parse.quote(op_id)}")

    def asset(self, asset_id: int):
        return self._request("GET", f"{API}/assets/v1/assets/{asset_id}?readMask=moderationResult")

    def image_id(self, decal_id: int) -> int | None:
        """The image behind a decal: asset delivery returns the decal's model, whose Texture names the image."""
        candidates = [
            ("json", f"{API}/asset-delivery-api/v1/assetId/{decal_id}"),
            ("raw", f"https://assetdelivery.roblox.com/v1/asset/?id={decal_id}"),
        ]
        for kind, url in candidates:
            status, body = self._request("GET", url)
            if status != 200:
                print(f"    image id lookup via {urllib.parse.urlparse(url).hostname}: HTTP {status}")
                continue
            content = body
            if kind == "json":
                try:
                    location = json.loads(body).get("location")
                except (ValueError, AttributeError):
                    location = None
                if not location:
                    continue
                status, content = self._request("GET", location)
                if status != 200:
                    continue
            found = parse_image_id(content, decal_id)
            if found:
                return found
        return None


def parse_image_id(content: bytes, decal_id: int) -> int | None:
    if content[:8] == b"\x89PNG\r\n\x1a\n" or content[:3] == b"\xff\xd8\xff":
        return decal_id  # the id already names an image
    text = content.decode("utf-8", "replace")
    for pattern in (r"<url>[^<]*?[?&]id=(\d+)[^<]*</url>", r"rbxassetid://(\d+)", r"<url>[^<]*?(\d{4,})\s*</url>"):
        m = re.search(pattern, text)
        if m and int(m.group(1)) != decal_id:
            return int(m.group(1))
    return None


def moderation_of(asset: dict) -> str:
    state = str(((asset or {}).get("moderationResult") or {}).get("moderationState") or "")
    upper = state.upper()
    if "REJECT" in upper:
        return "Rejected"
    if "REVIEW" in upper or "PENDING" in upper:
        return "Reviewing"
    return "Approved" if "APPROV" in upper or not upper else state


# -- run ------------------------------------------------------------------------------------------------------


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def used_this_month(log: dict, today: dt.datetime) -> int:
    """Uploads that reached Roblox this calendar month, including earlier attempts at a map (failed, rejected)."""
    month = today.strftime("%Y-%m")
    stamps = [s for rec in log["maps"].values() for s in [rec.get("uploadedAt", "")] + rec.get("history", [])]
    return sum(1 for s in stamps if str(s).startswith(month))


def settle(cloud: Cloud, key: str, rec: dict, wait: float) -> None:
    """Advances one uploaded map toward `ready`: finish the operation, check moderation, resolve the image id."""
    deadline = time.time() + wait
    delay = 1.5
    while rec["state"] == "processing":
        status, body = cloud.operation(rec["operation"])
        if status == 200:
            op = json.loads(body)
            if op.get("done"):
                if op.get("error"):
                    rec["state"] = "failed"
                    rec["error"] = str(op["error"].get("message", op["error"]))[:300]
                    print(f"  {key}: upload failed: {rec['error']}")
                    return
                asset = op.get("response") or {}
                rec["assetId"] = int(asset.get("assetId"))
                rec["returnedType"] = str(asset.get("assetType") or "")
                if rec.get("kind", "Decal") == "Image" and rec["returnedType"] and "IMAGE" not in rec["returnedType"].upper():
                    print(f"  {key}: asked for an Image, Roblox created {rec['returnedType']}; resolving it as a decal")
                    rec["kind"] = "Decal"
                if rec.get("kind", "Decal") != "Image":
                    rec["decalId"] = rec["assetId"]
                rec["moderation"] = moderation_of(asset)
                rec["state"] = "reviewing"
                break
        else:
            print(f"  {key}: operation poll HTTP {status}")
        if time.time() > deadline:
            print(f"  {key}: still processing; the next run picks it up")
            return
        time.sleep(delay)
        delay = min(delay * 1.6, 10)
    if rec["state"] == "reviewing" and rec.get("moderation") != "Approved":
        status, body = cloud.asset(rec.get("assetId") or rec["decalId"])
        if status == 200:
            rec["moderation"] = moderation_of(json.loads(body))
        if rec.get("moderation") == "Rejected":
            rec["state"] = "rejected"
            print(f"  {key}: rejected by moderation; it is retried only if the generator changes the map")
            return
        if rec.get("moderation") != "Approved":
            print(f"  {key}: under moderation review; the next run re-checks it")
            return
    if rec["state"] in ("reviewing", "unresolved") and rec.get("kind") == "Image":
        rec["imageId"] = rec["assetId"]
        rec["state"] = "ready"
        print(f"  {key}: ready (image {rec['imageId']})")
        return
    if rec["state"] in ("reviewing", "unresolved"):
        image = cloud.image_id(rec["decalId"])
        if image:
            rec["imageId"] = image
            rec["state"] = "ready"
            print(f"  {key}: ready (image {image})")
        else:
            rec["state"] = "unresolved"
            print(f"  {key}: uploaded, but its image id could not be resolved yet (give the API key asset read access)")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default=os.path.join(HERE, "manifest.json"))
    ap.add_argument("--out", default=os.path.join(HERE, "out"), help="generate.py output directory")
    ap.add_argument("--budget", type=int, default=100, help="image uploads allowed per calendar month")
    ap.add_argument("--dry-run", action="store_true", help="print the requests; send nothing, write nothing")
    ap.add_argument("--write-only", action="store_true", help="re-render TextureAssets.luau and the model file")
    ap.add_argument("--wait", type=float, default=90, help="seconds to wait for each upload operation")
    args = ap.parse_args()

    with open(args.manifest, encoding="utf-8") as fh:
        manifest = json.load(fh)
    log = read_log()
    if args.write_only:
        write_outputs(manifest, log)
        print("wrote", os.path.relpath(LUAU, ROOT), "and", os.path.relpath(MODEL, ROOT))
        return 0

    meta_path = os.path.join(args.out, "meta.json")
    if not os.path.exists(meta_path):
        print(f"{meta_path} is missing: run tools/textures/generate.py first")
        return 2
    with open(meta_path, encoding="utf-8") as fh:
        meta = json.load(fh)
    by_id = {m["id"]: m for m in manifest["materials"]}

    today = dt.datetime.now(dt.timezone.utc)
    used = used_this_month(log, today)
    remaining = max(0, args.budget - used)
    print(f"budget {args.budget}/month, {used} used in {today:%Y-%m}, {remaining} left")

    def superseded(rec: dict | None) -> bool:
        """An earlier upload of another asset type whose image id never resolved: it is uploaded again."""
        return bool(rec) and rec.get("state") == "unresolved" and rec.get("kind", "Decal") != manifest["assetType"]

    plan = []
    for key in manifest["uploadOrder"]:
        texture, map_name = key.split("/")
        rec = log["maps"].get(key)
        info = meta.get(texture, {}).get("files", {}).get(map_name)
        if info is None:
            print(f"  {key}: not generated (run generate.py)")
            continue
        if superseded(rec):
            plan.append((key, texture, map_name, info))
            continue
        if rec and rec.get("state") != "rejected" and rec.get("state") != "failed":
            if rec.get("sha256") != info["sha256"] and rec.get("state") == "ready":
                print(f"  {key}: generator output changed since upload; the uploaded version stays (no re-upload)")
            continue
        if rec and rec.get("state") == "rejected" and rec.get("sha256") == info["sha256"]:
            continue
        plan.append((key, texture, map_name, info))
    pending = [k for k, r in log["maps"].items() if r.get("state") in PENDING and not superseded(r)]
    print(f"{len(plan)} maps without an asset, {len(pending)} uploads to settle")

    if args.dry_run:
        for key, texture, map_name, info in plan[:remaining]:
            m = by_id[texture]
            request = {
                "assetType": manifest["assetType"],
                "displayName": f"Rovloc {texture} {map_name}",
                "description": m["description"][:1000],
                "creationContext": {"creator": {"userId": "<ROBLOX_CREATOR_ID>"}},
            }
            print(f"POST {API}/assets/v1/assets  x-api-key: <ROBLOX_API_KEY>")
            print(f"  request={json.dumps(request)}")
            print(f"  fileContent=@{info['file']} ({info['bytes']} bytes, image/png, sha256 {info['sha256'][:12]})")
        for key, *_ in plan[remaining:]:
            print(f"  over budget this month: {key}")
        for key in pending:
            print(f"GET {API}/assets/v1/operations|assets ... to settle {key} ({log['maps'][key]['state']})")
        return 0

    api_key = os.environ.get("ROBLOX_API_KEY", "")
    creator = os.environ.get("ROBLOX_CREATOR_ID", "")
    if not api_key or not creator:
        print("ROBLOX_API_KEY and ROBLOX_CREATOR_ID must be set (repository secrets)")
        return 2
    if not creator.isdigit():
        print("ROBLOX_CREATOR_ID must be the numeric Roblox user id")
        return 2
    cloud = Cloud(api_key, creator)

    for key in pending:
        settle(cloud, key, log["maps"][key], args.wait)
        write_outputs(manifest, log)

    uploaded = 0
    errors = 0
    for key, texture, map_name, info in plan:
        if uploaded >= remaining:
            print(f"  monthly budget reached; {key} and later maps wait for next month")
            break
        m = by_id[texture]
        path = os.path.join(args.out, info["file"])
        status, body = cloud.create(path, f"Rovloc {texture} {map_name}", m["description"][:1000], manifest["assetType"])
        if status != 200:
            snippet = body[:300].decode("utf-8", "replace")
            print(f"  {key}: create failed, HTTP {status}: {snippet}")
            errors += 1
            if status == 429 or errors >= 3:
                print("  stopping: rate limited or repeated errors (nothing recorded for the failed maps)")
                break
            continue
        errors = 0
        uploaded += 1
        op = json.loads(body)
        rec = {
            "state": "processing",
            "kind": manifest["assetType"],
            "operation": op.get("path", ""),
            "sha256": info["sha256"],
            "uploadedAt": now(),
        }
        previous = log["maps"].get(key)
        if previous:  # a failed or rejected earlier attempt still counts against its month
            rec["history"] = previous.get("history", []) + [previous.get("uploadedAt", "")]
        if map_name == "ColorMap":
            rec["reference"] = meta[texture]["reference"]
        log["maps"][key] = rec
        print(f"  {key}: uploaded ({info['bytes']} bytes)")
        settle(cloud, key, rec, args.wait)
        write_outputs(manifest, log)
        if manifest["assetType"] == "Image" and rec.get("kind") != "Image":
            print("  stopping: Roblox does not create Image assets for this key; the remaining maps are not uploaded")
            break
        time.sleep(1.0)

    write_outputs(manifest, log)
    ready = sum(1 for r in log["maps"].values() if r.get("state") == "ready")
    waiting = sum(1 for r in log["maps"].values() if r.get("state") in PENDING)
    summary = f"Textures: {uploaded} uploaded this run, {ready} ready in game, {waiting} waiting, {len(plan) - uploaded} not uploaded"
    print(summary)
    step = os.environ.get("GITHUB_STEP_SUMMARY")
    if step:
        with open(step, "a", encoding="utf-8") as fh:
            fh.write(summary + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
