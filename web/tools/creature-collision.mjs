// Generates web/src/creature/passthroughData.js: which collision vertices of each level only MonsterPassthrough
// parts use (see src/creature/monsterCollision.js). Run it after every world bake:
//
//   node tools/creature-collision.mjs [--raw build/cache/world-raw.json] [--build build]
//
// It replays the bake's collision build (tools/bake.mjs: every colliding static part of a level, in export order,
// through bake/mesh.mjs coarseTriangles, vertices deduplicated on 3-decimal keys), marks each vertex with the groups
// of the parts using it, and checks the result against the baked world (vertex and index counts, positions within
// the quantisation step) before writing. The fingerprint stored per level is taken from the decoded world.bin.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { coarseTriangles } from './bake/mesh.mjs';
import { decodeWorld } from '../src/engine/data.js';
import { fingerprint, monsterIndex } from '../src/creature/monsterCollision.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const webDir = path.resolve(here, '..');
const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};
const RAW = path.resolve(webDir, arg('raw', 'build/cache/world-raw.json'));
const BUILD = path.resolve(webDir, arg('build', 'build'));
const OUT = path.resolve(webDir, 'src/creature/passthroughData.js');
const PASSTHROUGH = 'MonsterPassthrough';

const raw = JSON.parse(fs.readFileSync(RAW, 'utf8'));
const meta = JSON.parse(fs.readFileSync(path.join(BUILD, 'world.json'), 'utf8'));
const bin = fs.readFileSync(path.join(BUILD, 'world.bin'));
const decoded = decodeWorld(meta, bin.buffer.slice(bin.byteOffset, bin.byteOffset + bin.byteLength));

/** @type {Record<string, any[]>} */
const byLevel = {};
for (const p of raw.parts) {
  if (!p.canCollide || p.entity) continue;
  (byLevel[p.level] ||= []).push(p);
}

const levels = {};
let failures = 0;
for (const [level, list] of Object.entries(byLevel)) {
  const table = meta.collision[level];
  const dec = decoded.collision[level];
  if (!table || !dec) {
    console.error(`[creature-collision] ${level}: not in the baked collision`);
    failures++;
    continue;
  }
  const map = new Map();
  /** @type {number[]} */
  const verts = [];
  /** @type {number[]} */
  const usage = []; // bit 1: a Default part uses the vertex, bit 2: a MonsterPassthrough part does
  let indexCount = 0;
  let passthroughTris = 0;
  for (const p of list) {
    const flat = [];
    coarseTriangles(p, flat);
    const bit = p.group === PASSTHROUGH ? 2 : 1;
    if (bit === 2) passthroughTris += flat.length / 9;
    for (let i = 0; i < flat.length; i += 3) {
      const key = `${flat[i].toFixed(3)},${flat[i + 1].toFixed(3)},${flat[i + 2].toFixed(3)}`;
      let vi = map.get(key);
      if (vi === undefined) {
        vi = verts.length / 3;
        map.set(key, vi);
        verts.push(flat[i], flat[i + 1], flat[i + 2]);
        usage.push(0);
      }
      usage[vi] |= bit;
      indexCount++;
    }
  }
  const vertexCount = verts.length / 3;
  if (vertexCount !== table.vertexCount || indexCount !== table.indexCount) {
    console.error(`[creature-collision] ${level}: replay gives ${vertexCount} vertices / ${indexCount} indices, the bake ${table.vertexCount} / ${table.indexCount}`);
    failures++;
    continue;
  }
  const step = table.quant.slice(3, 6);
  let worst = 0;
  for (let i = 0; i < vertexCount; i++) {
    for (let k = 0; k < 3; k++) {
      const err = Math.abs(dec.position[i * 3 + k] - verts[i * 3 + k]) / Math.max(step[k], 1e-9);
      if (err > worst) worst = err;
    }
  }
  if (worst > 1.01) {
    console.error(`[creature-collision] ${level}: replayed positions differ from world.bin by ${worst.toFixed(2)} quantisation steps`);
    failures++;
    continue;
  }
  const runs = [];
  let cursor = 0;
  for (let i = 0; i < vertexCount; ) {
    if (usage[i] !== 2) {
      i++;
      continue;
    }
    let j = i;
    while (j < vertexCount && usage[j] === 2) j++;
    runs.push(i - cursor, j - i);
    cursor = j;
    i = j;
  }
  const entry = { vertexCount, indexCount, fingerprint: fingerprint(dec.position), runs };
  const kept = monsterIndex(level, table, dec, { levels: { [level]: entry } });
  const dropped = kept ? (indexCount - kept.length) / 3 : 0;
  console.log(`[creature-collision] ${level.padEnd(20)} ${list.length} parts, ${indexCount / 3} triangles, ${passthroughTris} passthrough, ${dropped} dropped for the Creature (${runs.length / 2} runs)`);
  levels[level] = entry;
}

if (failures > 0) {
  console.error(`[creature-collision] ${failures} level(s) failed; ${path.relative(webDir, OUT)} not written`);
  process.exit(1);
}

const lines = [
  '// Generated by tools/creature-collision.mjs from build/cache/world-raw.json and build/world.json + world.bin. Do not',
  '// edit; run the tool again after a world bake. Per collision level: the counts and position fingerprint of the',
  '// decoded collision this describes, and the runs [gap, length, ...] of vertices only MonsterPassthrough parts use.',
  '',
  '/** @type {{levels: Record<string, {vertexCount: number, indexCount: number, fingerprint: number, runs: number[]}>}} */',
  'export const PASSTHROUGH = {',
  '  levels: {',
];
for (const [level, e] of Object.entries(levels)) {
  lines.push(`    ${JSON.stringify(level)}: {`);
  lines.push(`      vertexCount: ${e.vertexCount}, indexCount: ${e.indexCount}, fingerprint: ${e.fingerprint},`);
  lines.push('      runs: [');
  for (let i = 0; i < e.runs.length; i += 24) lines.push(`        ${e.runs.slice(i, i + 24).join(', ')},`);
  lines.push('      ],');
  lines.push('    },');
}
lines.push('  },', '};', '');
fs.writeFileSync(OUT, lines.join('\n'));
console.log(`[creature-collision] wrote ${path.relative(webDir, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(1)} KB)`);
