// recorded.mjs: the committed index of the renders for the Roblox port. render.mjs writes it from the merged manifest
// (web/build/audio/manifest.json, git-ignored) to src/ReplicatedStorage/Shared/Audio/RecordedSounds.luau, and
// web/tools/data-test.mjs compares the committed file with the manifest, so the port always knows exactly which files
// the website plays: every sound's variants (the shipped MP3s by their path under web/build/audio), their seconds,
// the loop region inside a looped file and its channels.

import path from 'node:path';
import { ROOT } from './voices.mjs';

export const RECORDED_SOUNDS = path.resolve(ROOT, '..', '..', 'src', 'ReplicatedStorage', 'Shared', 'Audio', 'RecordedSounds.luau');

const COLUMNS = 120;

const HEADER = `--!strict
-- GENERATED by web/sounds/render.mjs (npm run sounds) from the website's rendered sounds; never edited by hand
-- (web/tools/data-test.mjs compares it with web/build/audio/manifest.json).
--
-- The recorded files the game plays (docs/SOUND.md 11), name -> the sound's renders:
--   channels   1 (placed in the world) or 2 (heard all around you)
--   files      one per variant: the shipped MP3, by its path under web/build/audio
--   seconds    each variant's length as it plays (a loop: its period)
--   loop       a looped file's region in seconds: the file carries 100 ms of its own signal either side of it, so a
--              port loops this region (Sound.LoopRegion), never the whole file
-- A port uploads every file and plays the variants through the same preset metadata (SynthPresets: bus, roll-off,
-- priority, voice limits, the repeat of a pulse).

export type RecordedSound = {
	channels: number,
	files: { string },
	seconds: { number },
	loop: { start: number, finish: number }?,
}

local RecordedSounds: { [string]: RecordedSound } = {
`;

const num = (v) => String(+v.toFixed(4));
const quote = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/** `key = { a, b, c },` on one line at `indent` tabs when it fits in the column width, else one item a line. */
function list(indent, key, items) {
  const tabs = '\t'.repeat(indent);
  const one = `${tabs}${key} = { ${items.join(', ')} },`;
  // stylua counts a tab as 4 columns
  if (one.replace(/\t/g, '    ').length <= COLUMNS) return [one];
  return [`${tabs}${key} = {`, ...items.map((x) => `${tabs}\t${x},`), `${tabs}},`];
}

/**
 * RecordedSounds.luau for a merged manifest (render.mjs mergeManifests), as text.
 * @param {{sounds: Record<string, {channels: number, loop: boolean, variants: Array<{file: string, seconds: number, loop: {start: number, end: number}|null}>}>}} manifest
 */
export function recordedSoundsLuau(manifest) {
  const lines = [];
  for (const name of Object.keys(manifest.sounds).sort()) {
    const s = manifest.sounds[name];
    if (!s.variants.length) continue;
    lines.push(`\t${name} = {`, `\t\tchannels = ${s.channels},`);
    lines.push(...list(2, 'files', s.variants.map((v) => quote(v.file))));
    lines.push(...list(2, 'seconds', s.variants.map((v) => num(v.seconds))));
    const loop = s.variants[0].loop;
    if (loop) lines.push(`\t\tloop = { start = ${num(loop.start)}, finish = ${num(loop.end)} },`);
    lines.push('\t},');
  }
  return `${HEADER}${lines.join('\n')}\n}\n\nreturn table.freeze(RecordedSounds)\n`;
}
